/**
 * Header component
 * Application header with logo, theme toggle, and settings
 */

import { cn } from "../../lib/cn.js";
import { Button } from "../button.js";
import { useTheme } from "../../stores/index.js";

interface HeaderProps {
  className?: string;
  onSettingsClick?: () => void;
}

export function Header({ className, onSettingsClick }: HeaderProps) {
  const [theme, setTheme] = useTheme();

  const toggleTheme = () => {
    setTheme(theme === "dark" ? "light" : "dark");
  };

  return (
    <header
      className={cn(
        "flex items-center justify-between px-4 py-3 border-b bg-background",
        className
      )}
    >
      {/* Logo and title */}
      <div className="flex items-center gap-3">
        <div className="w-8 h-8 rounded-lg bg-primary flex items-center justify-center">
          <span className="text-primary-foreground font-bold text-sm">FP</span>
        </div>
        <div>
          <h1 className="text-lg font-semibold">Flatpack</h1>
          <p className="text-xs text-muted-foreground">NotebookLM Preprocessor</p>
        </div>
      </div>

      {/* Controls */}
      <div className="flex items-center gap-2">
        {/* Theme toggle */}
        <Button
          variant="ghost"
          size="icon"
          onClick={toggleTheme}
          aria-label={`Switch to ${theme === "dark" ? "light" : "dark"} mode`}
        >
          {theme === "dark" ? (
            <SunIcon className="h-4 w-4" />
          ) : (
            <MoonIcon className="h-4 w-4" />
          )}
        </Button>

        {/* Settings button */}
        {onSettingsClick && (
          <Button variant="ghost" size="icon" onClick={onSettingsClick} aria-label="Settings">
            <SettingsIcon className="h-4 w-4" />
          </Button>
        )}
      </div>
    </header>
  );
}

